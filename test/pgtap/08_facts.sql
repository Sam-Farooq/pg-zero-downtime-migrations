-- Size, indexes and standbys. The numbers here are catalogue arithmetic, and
-- the assertions are about the shape of the answer rather than about any
-- particular byte count, because the byte count depends on the page size and
-- on whether the table has been vacuumed.
BEGIN;
SELECT plan(14);

CREATE SCHEMA pgsafe_test;
CREATE TABLE pgsafe_test.orders (
    order_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference text NOT NULL,
    note      text
);
CREATE INDEX orders_reference_idx ON pgsafe_test.orders (reference);
INSERT INTO pgsafe_test.orders (reference, note)
    SELECT 'R' || g, 'n' || g FROM generate_series(1, 200) AS g;
ANALYZE pgsafe_test.orders;

SELECT is(
    (SELECT f.estimated_rows FROM pgsafe.table_facts('pgsafe_test.orders') AS f),
    200::bigint,
    'after ANALYZE the estimate is the row count'
);
SELECT is(
    (SELECT f.index_count FROM pgsafe.table_facts('pgsafe_test.orders') AS f),
    2,
    'the primary key and the one index are both counted'
);
SELECT ok(
    (SELECT f.total_bytes >= f.heap_bytes + f.index_bytes - 8192
       FROM pgsafe.table_facts('pgsafe_test.orders') AS f),
    'the total covers the heap and the indexes'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.table_facts('pgsafe_test.orders_reference_idx')$$,
    '42809',
    NULL,
    'an index is not a table'
);

SELECT ok(
    (SELECT e.seconds > 0 FROM pgsafe.rewrite_estimate('pgsafe_test.orders') AS e),
    'a rewrite of a table with rows in it takes a non zero amount of time'
);
SELECT ok(
    (SELECT e.affordable FROM pgsafe.rewrite_estimate('pgsafe_test.orders') AS e),
    'and 200 rows is affordable by any budget'
);
SELECT ok(
    NOT (SELECT e.affordable
           FROM pgsafe.rewrite_estimate('pgsafe_test.orders', 1024, 0.001) AS e),
    'while a kilobyte a second and a millisecond budget is not'
);
SELECT ok(
    (SELECT e.assumption FROM pgsafe.rewrite_estimate('pgsafe_test.orders') AS e)
        LIKE '%Measure on a copy%',
    'and the answer says what it assumed'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.rewrite_estimate('pgsafe_test.orders', 0)$$,
    '22023',
    NULL,
    'a throughput of zero is refused rather than dividing by it'
);

-- unused_indexes reads the statistics views, which are shared memory rather
-- than catalogue rows, so an index created in an open transaction may or may
-- not have a counter yet. All that can be asserted from here is that the query
-- runs and that an enforcement index is never offered for removal.
SELECT lives_ok(
    $$SELECT * FROM pgsafe.unused_indexes()$$,
    'unused_indexes() runs'
);
SELECT is_empty(
    $$SELECT index_name FROM pgsafe.unused_indexes() WHERE index_name LIKE '%_pkey'$$,
    'and never offers to drop a primary key, whatever its scan count'
);

-- With no standby connected, replication_lag() returns nothing and the wait
-- returns at once. That is the honest answer rather than zero lag.
SELECT is_empty(
    $$SELECT client FROM pgsafe.replication_lag()$$,
    'replication_lag() reports nothing rather than zero when no standby is connected'
);
SELECT is(
    pgsafe.wait_for_replication(),
    interval '0',
    'the replication wait returns immediately when there are no standbys'
);
SELECT throws_ok(
    $$SELECT pgsafe.wait_for_replication(interval '5 seconds', interval '1 minute', 0)$$,
    '22023',
    NULL,
    'a poll interval of zero is refused rather than spinning'
);

SELECT * FROM finish();
ROLLBACK;
