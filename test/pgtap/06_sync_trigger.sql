-- The dual write trigger, which is the part of an expand and contract rename
-- that has to be right while two versions of an application are both live.
BEGIN;
SELECT plan(14);

CREATE SCHEMA pgsafe_test;
CREATE TABLE pgsafe_test.pair (
    pair_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_name text,
    new_name text
);
CREATE TRIGGER pair_sync
    BEFORE INSERT OR UPDATE ON pgsafe_test.pair
    FOR EACH ROW EXECUTE FUNCTION pgsafe.sync_column_pair('old_name', 'new_name');

-- A writer that knows only the old name.
INSERT INTO pgsafe_test.pair (pair_id, old_name) VALUES (1, 'written old');
SELECT is(
    (SELECT new_name FROM pgsafe_test.pair WHERE pair_id = 1),
    'written old',
    'an insert naming only the old column fills the new one'
);

-- A writer that has been deployed and knows only the new name.
INSERT INTO pgsafe_test.pair (pair_id, new_name) VALUES (2, 'written new');
SELECT is(
    (SELECT old_name FROM pgsafe_test.pair WHERE pair_id = 2),
    'written new',
    'an insert naming only the new column fills the old one'
);

-- Both, agreeing.
INSERT INTO pgsafe_test.pair (pair_id, old_name, new_name) VALUES (3, 'same', 'same');
SELECT is(
    (SELECT old_name || '/' || new_name FROM pgsafe_test.pair WHERE pair_id = 3),
    'same/same',
    'an insert naming both with the same value is left alone'
);

-- Neither.
INSERT INTO pgsafe_test.pair (pair_id) VALUES (4);
SELECT ok(
    (SELECT old_name IS NULL AND new_name IS NULL FROM pgsafe_test.pair WHERE pair_id = 4),
    'an insert naming neither leaves both null rather than inventing a value'
);

-- Both, disagreeing. This is a bug in the caller and it is not papered over.
SELECT throws_ok(
    $$INSERT INTO pgsafe_test.pair (pair_id, old_name, new_name) VALUES (5, 'a', 'b')$$,
    '23000',
    NULL,
    'an insert naming both with different values is refused'
);

-- Updates, from either side.
UPDATE pgsafe_test.pair SET old_name = 'moved old' WHERE pair_id = 1;
SELECT is(
    (SELECT new_name FROM pgsafe_test.pair WHERE pair_id = 1),
    'moved old',
    'an update to the old column follows through to the new one'
);

UPDATE pgsafe_test.pair SET new_name = 'moved new' WHERE pair_id = 2;
SELECT is(
    (SELECT old_name FROM pgsafe_test.pair WHERE pair_id = 2),
    'moved new',
    'and an update to the new column follows through to the old one'
);

UPDATE pgsafe_test.pair SET old_name = 'both', new_name = 'both' WHERE pair_id = 3;
SELECT is(
    (SELECT old_name || '/' || new_name FROM pgsafe_test.pair WHERE pair_id = 3),
    'both/both',
    'an update writing both with one value is fine'
);

SELECT throws_ok(
    $$UPDATE pgsafe_test.pair SET old_name = 'x', new_name = 'y' WHERE pair_id = 3$$,
    '23000',
    NULL,
    'an update writing both with different values is refused'
);

-- Setting a column back to null is a write like any other, and the pair has to
-- follow. A trigger that tested value IS NULL instead of jsonb null would read
-- this as "nothing was supplied" and leave the two columns different.
UPDATE pgsafe_test.pair SET old_name = NULL WHERE pair_id = 1;
SELECT ok(
    (SELECT new_name IS NULL FROM pgsafe_test.pair WHERE pair_id = 1),
    'clearing one column clears the other'
);

-- A row that already has both values and is updated elsewhere is untouched.
UPDATE pgsafe_test.pair SET pair_id = 33 WHERE pair_id = 3;
SELECT is(
    (SELECT old_name || '/' || new_name FROM pgsafe_test.pair WHERE pair_id = 33),
    'both/both',
    'an update that touches neither column of the pair changes neither'
);

-- Misuse is refused rather than silently doing nothing.
CREATE TABLE pgsafe_test.wrong (wrong_id bigint PRIMARY KEY, a text, b text);
CREATE TRIGGER wrong_arity
    BEFORE INSERT ON pgsafe_test.wrong
    FOR EACH ROW EXECUTE FUNCTION pgsafe.sync_column_pair('a');
SELECT throws_ok(
    $$INSERT INTO pgsafe_test.wrong (wrong_id, a) VALUES (1, 'x')$$,
    '22023',
    NULL,
    'a trigger created with one column name is refused when it fires'
);

CREATE TABLE pgsafe_test.absent_column (absent_id bigint PRIMARY KEY, a text);
CREATE TRIGGER absent_pair
    BEFORE INSERT ON pgsafe_test.absent_column
    FOR EACH ROW EXECUTE FUNCTION pgsafe.sync_column_pair('a', 'not_here');
SELECT throws_ok(
    $$INSERT INTO pgsafe_test.absent_column (absent_id, a) VALUES (1, 'x')$$,
    '42703',
    NULL,
    'and so is a pair naming a column the table does not have'
);

SELECT is(
    (SELECT count(*) FROM pgsafe_test.pair)::bigint,
    4::bigint,
    'the refused inserts left nothing behind'
);

SELECT * FROM finish();
ROLLBACK;
