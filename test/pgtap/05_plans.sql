-- The generators. Every assertion here is about the text of a plan, which is
-- what somebody is going to paste into psql.
BEGIN;
SELECT plan(40);

CREATE SCHEMA pgsafe_test;
CREATE TABLE pgsafe_test.orders (
    order_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL,
    reference   varchar(32) NOT NULL,
    amount      integer NOT NULL,
    note        text
);
CREATE TABLE pgsafe_test.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text NOT NULL
);
CREATE TABLE pgsafe_test.composite (
    left_id  bigint,
    right_id bigint,
    PRIMARY KEY (left_id, right_id)
);
CREATE TABLE pgsafe_test.keyless (anything text);
CREATE INDEX orders_reference_idx ON pgsafe_test.orders (reference);
INSERT INTO pgsafe_test.orders (customer_id, reference, amount, note)
    SELECT 1, 'R' || g, g, CASE WHEN g % 2 = 0 THEN NULL ELSE 'n' END
      FROM generate_series(1, 10) AS g;

-- plan_set_not_null
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note'))::bigint,
    4::bigint,
    'the NOT NULL plan is four statements'
);
SELECT is(
    (SELECT array_agg(tx ORDER BY step) FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note')),
    ARRAY[1, 2, 3, 4],
    'each one in its own transaction'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note') WHERE step = 1)
        LIKE '%CHECK (note IS NOT NULL) NOT VALID;',
    'step one adds the CHECK without validating it'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note') WHERE step = 2)
        LIKE '%VALIDATE CONSTRAINT%',
    'step two validates it'
);
SELECT is(
    (SELECT work FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note') WHERE step = 2),
    'scan',
    'and step two is the one that scans'
);
SELECT is(
    (SELECT lock_mode FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note') WHERE step = 2),
    'SHARE UPDATE EXCLUSIVE',
    'under the lock that lets traffic through'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note') WHERE step = 3)
        LIKE '%ALTER COLUMN note SET NOT NULL;',
    'step three is the SET NOT NULL that no longer scans'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'note', NULL, false))::bigint,
    3::bigint,
    'dropping the redundant CHECK is optional'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'customer_id'))::bigint,
    0::bigint,
    'a column that is already NOT NULL needs no plan'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.plan_set_not_null('pgsafe_test.orders', 'nope')$$,
    '42703',
    NULL,
    'a column that does not exist is refused'
);

-- plan_add_column
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_add_column('pgsafe_test.orders', 'is_gift', 'boolean', 'false', true))::bigint,
    1::bigint,
    'a constant default needs one statement, whatever the table size'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_add_column('pgsafe_test.orders', 'public_id', 'uuid', 'gen_random_uuid()', true))::bigint,
    7::bigint,
    'a volatile default needs seven, across seven transactions'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_add_column('pgsafe_test.orders', 'public_id', 'uuid', 'gen_random_uuid()', true) WHERE step = 3)
        LIKE '%COMMIT;%',
    'the backfill step commits each batch'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_add_column('pgsafe_test.orders', 'public_id', 'uuid', 'gen_random_uuid()', true, 250) WHERE step = 3)
        LIKE '%LIMIT 250%',
    'and takes the batch size it was given'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.plan_add_column('pgsafe_test.orders', 'note', 'text')$$,
    '42701',
    NULL,
    'a column that already exists is refused'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.plan_add_column('pgsafe_test.orders', 'c', 'nonesuch')$$,
    '42704',
    NULL,
    'and so is a type the server does not know'
);

-- not_null_steps
--
-- Separate from plan_set_not_null on purpose, and these are the assertions that
-- say why. plan_add_column delegates here for a column that does not exist yet,
-- because the steps above it in that plan are the ones that create it. It used
-- to delegate to plan_set_not_null, which refuses a column it cannot find, so
-- `plan_add_column(..., p_not_null := true)` raised undefined_column every time
-- and the whole branch was dead.
SELECT is(
    (SELECT count(*) FROM pgsafe.not_null_steps('pgsafe_test.orders', 'not_a_column'))::bigint,
    4::bigint,
    'not_null_steps plans for a column that does not exist, which is the point of it'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.not_null_steps('pgsafe_test.orders', 'not_a_column', NULL, false))::bigint,
    3::bigint,
    'and drops the optional DROP CONSTRAINT when it is told not to'
);
SELECT ok(
    (SELECT statement FROM pgsafe.not_null_steps('pgsafe_test.orders', 'not_a_column') WHERE step = 1)
        LIKE '%NOT VALID;',
    'the CHECK goes on NOT VALID so nothing scans under the lock'
);
SELECT ok(
    (SELECT statement FROM pgsafe.not_null_steps('pgsafe_test.orders', 'c', 'my_check') WHERE step = 1)
        LIKE '%ADD CONSTRAINT my_check %',
    'and an explicit constraint name is used rather than the derived one'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_add_column('pgsafe_test.orders', 'public_id', 'uuid', 'gen_random_uuid()', true))::bigint,
    7::bigint,
    'so plan_add_column with p_not_null builds a plan rather than raising'
);

-- plan_change_type
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_change_type('pgsafe_test.orders', 'reference', 'varchar(64)'))::bigint,
    1::bigint,
    'a relabel is one statement'
);
SELECT is(
    (SELECT work FROM pgsafe.plan_change_type('pgsafe_test.orders', 'reference', 'varchar(64)')),
    'index_build',
    'and it still rebuilds the indexes on the column'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_change_type('pgsafe_test.orders', 'amount', 'bigint'))::bigint,
    6::bigint,
    'integer to bigint has to replace the column, which takes six steps'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_change_type('pgsafe_test.orders', 'amount', 'bigint') WHERE step = 2)
        LIKE '%sync_column_pair%',
    'one of which is the dual write trigger'
);

-- plan_rename_column
SELECT ok(
    (SELECT statement FROM pgsafe.plan_rename_column('pgsafe_test.orders', 'note', 'customer_note') WHERE step = 1)
        LIKE 'ALTER TABLE%ADD COLUMN customer_note text;',
    'a rename starts by adding the new name with the old type'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.plan_rename_column('pgsafe_test.orders', 'note', 'customer_note')
      WHERE work = 'deploy')::bigint,
    1::bigint,
    'and it includes a step that is a deploy rather than a statement'
);

-- plan_create_index and plan_add_foreign_key
SELECT ok(
    (SELECT statement FROM pgsafe.plan_create_index('pgsafe_test.orders', ARRAY['customer_id']::name[]) WHERE step = 1)
        LIKE 'CREATE INDEX CONCURRENTLY%',
    'an index plan builds concurrently'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_create_index('pgsafe_test.orders', ARRAY['reference']::name[], true) WHERE step = 3)
        LIKE '%UNIQUE USING INDEX%',
    'and a unique constraint adopts the index rather than building another'
);
SELECT ok(
    (SELECT statement FROM pgsafe.plan_add_foreign_key('pgsafe_test.orders', 'customer_id', 'pgsafe_test.customers') WHERE step = 1)
        LIKE '%REFERENCES pgsafe_test.customers (customer_id) NOT VALID;',
    'a foreign key plan finds the parent key and adds the constraint NOT VALID'
);
SELECT throws_ok(
    $$SELECT pgsafe.primary_key_column('pgsafe_test.composite')$$,
    '0A000',
    NULL,
    'the generated backfill walks one column, and a composite key is refused rather than fudged'
);

SELECT throws_ok(
    $$SELECT pgsafe.primary_key_column('pgsafe_test.keyless')$$,
    '42704',
    NULL,
    'and so is a table with no primary key at all'
);

-- The small readers the plans are built out of.
SELECT is(
    pgsafe.column_type('pgsafe_test.orders', 'reference'),
    'character varying(32)',
    'column_type reads the declared type with its modifier'
);
SELECT is(
    (pgsafe.column_type_change('pgsafe_test.orders', 'amount', 'bigint')).cost,
    'rewrite',
    'the verdict for a live column reads its current type from the catalogue'
);
SELECT is(
    pgsafe.relation_name('pgsafe_test.orders')::text,
    'orders',
    'relation_name drops the schema, so a generated constraint name is stable'
);
SELECT ok(
    pgsafe.backfill_loop('pgsafe_test.orders', 'note = ''x''', 'note IS NULL', 2000)
        LIKE '%LIMIT 2000%ORDER BY%' OR
    pgsafe.backfill_loop('pgsafe_test.orders', 'note = ''x''', 'note IS NULL', 2000)
        LIKE '%ORDER BY%LIMIT 2000%',
    'backfill_loop walks the primary key in order'
);
SELECT throws_ok(
    $$SELECT pgsafe.backfill_loop('pgsafe_test.orders', 'note = ''x''', 'note IS NULL', 0)$$,
    '22023',
    NULL,
    'and refuses a batch size of zero, which would loop forever'
);

-- column_dependents, which is the list a rename has to deal with by hand
SELECT is(
    (SELECT count(*) FROM pgsafe.column_dependents('pgsafe_test.orders', 'reference')
      WHERE kind = 'index')::bigint,
    1::bigint,
    'column_dependents finds the index that names the column'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.column_dependents('pgsafe_test.orders', 'nope')$$,
    '42703',
    NULL,
    'and refuses a column that is not there'
);

-- A plan cannot invent a lock mode: it has to name a form the table holds.
SELECT throws_ok(
    $$SELECT pgsafe.form_lock('not_a_real_form')$$,
    '42704',
    NULL,
    'form_lock refuses an unknown statement form'
);

SELECT * FROM finish();
ROLLBACK;
