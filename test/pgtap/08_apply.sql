-- Applying a plan, and the log it leaves.
--
-- Every call here is a dry run. A real run commits, and a procedure cannot
-- COMMIT inside a transaction block, so the committing path cannot be reached
-- from inside a pgTAP transaction. What is tested here is the ordering, the
-- log, and the two refusals.
BEGIN;
SELECT plan(14);

CREATE SCHEMA pgsafe_test;
CREATE TABLE pgsafe_test.orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note     text
);
INSERT INTO pgsafe_test.orders (note)
    SELECT CASE WHEN g % 3 = 0 THEN NULL ELSE 'n' || g END FROM generate_series(1, 9) AS g;

SELECT throws_ok(
    $$CALL pgsafe.apply_plan('', 'SELECT 1', '3s', 5, interval '2 seconds', true)$$,
    '22023',
    NULL,
    'a migration has to be named, so the log can be read afterwards'
);

CALL pgsafe.apply_plan(
    'not_null_on_note',
    'SELECT * FROM pgsafe.plan_set_not_null(''pgsafe_test.orders'', ''note'')',
    '3s', 5, interval '2 seconds', true
);

SELECT is(
    (SELECT count(*) FROM pgsafe.migration_log WHERE migration = 'not_null_on_note')::bigint,
    4::bigint,
    'the dry run logged all four steps'
);
SELECT is(
    (SELECT count(DISTINCT outcome) FROM pgsafe.migration_log
      WHERE migration = 'not_null_on_note')::bigint,
    1::bigint,
    'all of them with one outcome'
);
SELECT is(
    (SELECT DISTINCT outcome FROM pgsafe.migration_log WHERE migration = 'not_null_on_note'),
    'planned',
    'and that outcome is planned rather than done'
);
SELECT is(
    (SELECT array_agg(tx ORDER BY step) FROM pgsafe.migration_log
      WHERE migration = 'not_null_on_note'),
    ARRAY[1, 2, 3, 4],
    'the transaction boundaries are carried into the log'
);
SELECT ok(
    (SELECT note FROM pgsafe.migration_log WHERE migration = 'not_null_on_note' AND step = 2)
        LIKE '%own transaction%',
    'with the note that says why each step is separate'
);
SELECT ok(
    (SELECT NOT a.attnotnull FROM pg_attribute a
      WHERE a.attrelid = 'pgsafe_test.orders'::regclass AND a.attname = 'note'),
    'and nothing ran: the column is still nullable'
);

-- A plan with a deploy boundary in it stops there rather than running on.
CALL pgsafe.apply_plan(
    'rename_note',
    'SELECT * FROM pgsafe.plan_rename_column(''pgsafe_test.orders'', ''note'', ''customer_note'')',
    '3s', 5, interval '2 seconds', true
);

SELECT is(
    (SELECT count(*) FROM pgsafe.migration_log WHERE migration = 'rename_note')::bigint,
    4::bigint,
    'the rename plan stopped at its deploy boundary instead of logging all six steps'
);
SELECT is(
    (SELECT outcome FROM pgsafe.migration_log WHERE migration = 'rename_note' AND step = 4),
    'stopped',
    'and the boundary itself is recorded as stopped'
);
SELECT is(
    (SELECT statement FROM pgsafe.migration_log WHERE migration = 'rename_note' AND step = 4),
    NULL,
    'with no statement, because a deploy is not one'
);

-- The report, and the refusals around it.
SELECT is(
    (SELECT count(*) FROM pgsafe.migration_report('not_null_on_note'))::bigint,
    4::bigint,
    'the report returns a row per logged step'
);
SELECT is(
    (SELECT array_agg(step ORDER BY step) FROM pgsafe.migration_report('not_null_on_note')),
    ARRAY[1, 2, 3, 4],
    'in step order'
);
SELECT throws_ok(
    $$SELECT * FROM pgsafe.migration_report('never_ran')$$,
    'P0002',
    NULL,
    'and refuses a migration it has never seen rather than returning nothing'
);

-- A dry run finishes every row it writes, so nothing is left hanging.
SELECT is_empty(
    $$SELECT migration FROM pgsafe.unfinished_steps()$$,
    'no step is left at running after a dry run'
);

SELECT * FROM finish();
ROLLBACK;
