-- The guards, against a scratch table in its own schema.
BEGIN;
SELECT plan(25);

CREATE SCHEMA pgsafe_test;
CREATE TABLE pgsafe_test.guard (
    guard_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note     text
);
INSERT INTO pgsafe_test.guard (note) SELECT 'n' || g FROM generate_series(1, 20) AS g;

SELECT ok(pgsafe.expression_is_volatile('gen_random_uuid()'), 'gen_random_uuid() is volatile');
SELECT ok(pgsafe.expression_is_volatile('coalesce(note, random()::text)'), 'and so is a nested call');
SELECT ok(pgsafe.expression_is_volatile('nextval(''pgsafe_test.s'')'), 'a sequence read is volatile');
SELECT ok(NOT pgsafe.expression_is_volatile('now()'), 'now() is stable, so a default using it is free');
SELECT ok(NOT pgsafe.expression_is_volatile('false'), 'a literal calls nothing');
SELECT ok(NOT pgsafe.expression_is_volatile(NULL), 'no default is not a volatile default');

SET lock_timeout = '7s';

SELECT is(
    (pgsafe.run_guarded('ALTER TABLE pgsafe_test.guard ADD COLUMN extra integer')).attempts,
    1,
    'the statement lands on the first attempt when nothing holds the table'
);
SELECT has_column('pgsafe_test', 'guard', 'extra', 'and the statement really ran');
SELECT is(
    current_setting('lock_timeout'),
    '7s',
    'the lock_timeout that was there before is put back'
);

SELECT throws_ok(
    $$SELECT pgsafe.run_guarded('CREATE INDEX CONCURRENTLY i ON pgsafe_test.guard (note)')$$,
    '0A000',
    NULL,
    'CONCURRENTLY is refused rather than attempted inside a transaction'
);
SELECT throws_ok(
    $$SELECT pgsafe.run_guarded('SELECT 1', '3s', 0)$$,
    '22023',
    NULL,
    'zero attempts is a programming error'
);
SELECT throws_ok(
    $$SELECT pgsafe.run_guarded('ALTER TABLE pgsafe_test.absent ADD COLUMN c integer')$$,
    '42P01',
    NULL,
    'an error that is not a lock timeout is raised rather than retried'
);

CREATE INDEX guard_note_idx ON pgsafe_test.guard (note);

SELECT lives_ok(
    $$SELECT pgsafe.assert_index_valid('pgsafe_test.guard_note_idx')$$,
    'a valid index passes the check'
);
SELECT throws_ok(
    $$SELECT pgsafe.assert_index_valid('pgsafe_test.guard')$$,
    '42704',
    NULL,
    'a table is not an index'
);
SELECT is_empty(
    $$SELECT index_name FROM pgsafe.invalid_indexes()$$,
    'no index in this database was left behind by a failed build'
);

ALTER TABLE pgsafe_test.guard
    ADD CONSTRAINT guard_note_not_null CHECK (note IS NOT NULL) NOT VALID;

SELECT is(
    (SELECT count(*) FROM pgsafe.unvalidated_constraints()
      WHERE constraint_name = 'guard_note_not_null')::bigint,
    1::bigint,
    'a constraint added NOT VALID is reported'
);
SELECT ok(
    (SELECT validate_statement FROM pgsafe.unvalidated_constraints()
      WHERE constraint_name = 'guard_note_not_null') LIKE 'ALTER TABLE%VALIDATE CONSTRAINT%',
    'with the statement that finishes the job'
);
SELECT is(
    (SELECT constraint_kind FROM pgsafe.unvalidated_constraints()
      WHERE constraint_name = 'guard_note_not_null'),
    'check',
    'and its kind spelled out'
);

ALTER TABLE pgsafe_test.guard VALIDATE CONSTRAINT guard_note_not_null;

SELECT is_empty(
    $$SELECT constraint_name FROM pgsafe.unvalidated_constraints()$$,
    'and it stops being reported once it is validated'
);

SELECT is(
    (SELECT count(*) FROM pgsafe.preflight())::bigint,
    3::bigint,
    'preflight asks three questions'
);
SELECT ok(
    (SELECT p.ok FROM pgsafe.preflight() AS p WHERE p.check_name = 'invalid_indexes'),
    'and the invalid index question answers yes here'
);
SELECT ok(
    (SELECT p.ok FROM pgsafe.preflight() AS p WHERE p.check_name = 'unvalidated_constraints'),
    'as does the unvalidated constraint question, now that it is validated'
);

-- blockers() and lock_queue() need another session to say anything useful. All
-- that can be checked from one connection is that they run and exclude this
-- backend, which is why neither is asserted on beyond that.
SELECT lives_ok(
    $$SELECT * FROM pgsafe.blockers('pgsafe_test.guard')$$,
    'blockers() runs with a single connection and reports nothing'
);
SELECT lives_ok(
    $$SELECT * FROM pgsafe.lock_queue()$$,
    'lock_queue() runs with nothing waiting'
);
SELECT lives_ok(
    $$SELECT * FROM pgsafe.long_running_transactions(interval '1 second')$$,
    'long_running_transactions() runs and excludes this backend'
);

SELECT * FROM finish();
ROLLBACK;
