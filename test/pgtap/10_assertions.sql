-- The data questions, asked with a SELECT instead of with a lock.
BEGIN;
SELECT plan(22);

CREATE SCHEMA pgsafe_test;
CREATE TABLE pgsafe_test.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       varchar(10) NOT NULL
);
CREATE TABLE pgsafe_test.orders (
    order_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint,
    reference   varchar(10) NOT NULL,
    amount_text text NOT NULL,
    note        text
);

INSERT INTO pgsafe_test.customers (customer_id, email)
    SELECT g, 'c' || g FROM generate_series(1, 3) AS g;

-- Nine orders: three with no note, one pointing at a customer that does not
-- exist, two sharing a reference, and one amount that is not a number.
INSERT INTO pgsafe_test.orders (customer_id, reference, amount_text, note) VALUES
    (1, 'R1', '100', 'a'),
    (1, 'R2', '200', NULL),
    (2, 'R3', '300', 'c'),
    (2, 'R4', '400', NULL),
    (3, 'R5', '500', 'e'),
    (3, 'R6', '600', NULL),
    (99, 'R7', '700', 'g'),
    (1, 'R8', '800', 'h'),
    (2, 'R8', 'not a number', 'i');

-- Nulls, which is what SET NOT NULL scans for under ACCESS EXCLUSIVE.
SELECT is(
    pgsafe.null_count('pgsafe_test.orders', 'note'),
    3::bigint,
    'the null count is the number of rows SET NOT NULL would fail on'
);
SELECT throws_ok(
    $$SELECT pgsafe.assert_no_nulls('pgsafe_test.orders', 'note')$$,
    '23502',
    NULL,
    'and the assertion raises rather than returning a number nobody read'
);
SELECT is(
    pgsafe.null_count('pgsafe_test.orders', 'reference'),
    0::bigint,
    'a column with no nulls counts zero'
);
SELECT lives_ok(
    $$SELECT pgsafe.assert_no_nulls('pgsafe_test.orders', 'reference')$$,
    'and passes the assertion'
);
SELECT throws_ok(
    $$SELECT pgsafe.null_count('pgsafe_test.orders', 'absent')$$,
    '42703',
    NULL,
    'a column that does not exist is refused rather than counted as zero'
);

-- Orphans, which is what VALIDATE CONSTRAINT scans for.
SELECT is(
    pgsafe.orphan_count('pgsafe_test.orders', 'customer_id', 'pgsafe_test.customers'),
    1::bigint,
    'the orphan count finds the row that would fail a foreign key validation'
);
SELECT throws_ok(
    $$SELECT pgsafe.assert_no_orphans('pgsafe_test.orders', 'customer_id', 'pgsafe_test.customers')$$,
    '23503',
    NULL,
    'and the assertion raises with the foreign key code'
);

UPDATE pgsafe_test.orders SET customer_id = NULL WHERE customer_id = 99;

SELECT is(
    pgsafe.orphan_count('pgsafe_test.orders', 'customer_id', 'pgsafe_test.customers'),
    0::bigint,
    'a null referencing column is not an orphan, which is how MATCH SIMPLE reads it'
);
SELECT lives_ok(
    $$SELECT pgsafe.assert_no_orphans('pgsafe_test.orders', 'customer_id', 'pgsafe_test.customers')$$,
    'so the assertion now passes'
);

-- Duplicates, which is what a concurrent unique build fails on after two passes.
SELECT is(
    pgsafe.duplicate_count('pgsafe_test.orders', ARRAY['reference']::name[]),
    1::bigint,
    'one duplicate group in the reference column'
);
SELECT throws_ok(
    $$SELECT pgsafe.assert_unique('pgsafe_test.orders', ARRAY['reference']::name[])$$,
    '23505',
    NULL,
    'and the assertion raises with the unique violation code'
);
SELECT is(
    pgsafe.duplicate_count('pgsafe_test.orders', ARRAY['order_id']::name[]),
    0::bigint,
    'the primary key has none'
);
SELECT throws_ok(
    $$SELECT pgsafe.duplicate_count('pgsafe_test.orders', NULL)$$,
    '22023',
    NULL,
    'and no columns at all is a programming error'
);

-- Values a type change would reject.
SELECT ok(pgsafe.value_fits('42', 'integer'), '42 fits an integer');
SELECT ok(NOT pgsafe.value_fits('not a number', 'integer'), 'a word does not');
SELECT ok(pgsafe.value_fits(NULL, 'integer'), 'and a null fits anything, because the cast is never run');
SELECT ok(NOT pgsafe.value_fits('123456789012345', 'varchar(3)'), 'a value longer than the limit does not fit');
SELECT throws_ok(
    $$SELECT pgsafe.value_fits('42', 'nonesuch')$$,
    '42704',
    NULL,
    'a target type the server does not know is refused'
);
SELECT is(
    pgsafe.unconvertible_count('pgsafe_test.orders', 'amount_text', 'integer'),
    1::bigint,
    'one row would stop ALTER COLUMN TYPE integer, after it had rewritten the rest'
);

-- And the whole set, for the table.
SELECT is(
    (SELECT count(*) FROM pgsafe.data_preflight('pgsafe_test.orders'))::bigint,
    1::bigint,
    'with no column named, the data preflight reports the size and stops'
);
SELECT is(
    (SELECT count(*) FROM pgsafe.data_preflight('pgsafe_test.orders', 'reference', 'varchar(20)'))::bigint,
    4::bigint,
    'with a column and a target type it asks four questions'
);
SELECT is_empty(
    $$SELECT check_name FROM pgsafe.data_preflight('pgsafe_test.orders', 'reference', 'varchar(20)')
       WHERE NOT ok$$,
    'and all four pass for a widening on a column with no nulls'
);

SELECT * FROM finish();
ROLLBACK;
