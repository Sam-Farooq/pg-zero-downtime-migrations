-- 07_apply.sql
--
-- Running a plan, and recording what happened.
--
-- The generators in 05_plans.sql return one row per statement with the
-- transaction boundaries numbered, which is a shape no migration file can
-- express: a file is one script and the boundaries are the point. A PROCEDURE
-- can, because since PostgreSQL 11 a procedure called at the top level may
-- COMMIT, and that is the only construct in the database that can.
--
-- The log is written in two steps on purpose. The row for a statement is
-- inserted and committed BEFORE the statement runs, and updated to done
-- afterwards in the same transaction as the statement itself. So a step that
-- fails leaves a row that says it started and never finished, which is the
-- record somebody wants at 3am, and a step that succeeds commits its DDL and
-- its log row together or not at all.
--
-- There is deliberately no exception handler in the procedure. A COMMIT is not
-- allowed while a subtransaction is active, so a handler would have to choose
-- between logging the failure and committing the work, and the two step insert
-- above already answers the question a handler would have been for.

CREATE TABLE IF NOT EXISTS pgsafe.migration_log (
    log_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration     text NOT NULL,
    step          integer NOT NULL,
    tx            integer NOT NULL,
    statement     text,
    lock_mode     text,
    work          text,
    note          text,
    started_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at   timestamptz,
    attempts      integer,
    outcome       text NOT NULL DEFAULT 'running'
                  CHECK (outcome IN ('running', 'done', 'planned', 'stopped')),
    acting_user   name NOT NULL DEFAULT current_user
);

CREATE INDEX IF NOT EXISTS migration_log_migration_idx
    ON pgsafe.migration_log (migration, step);

COMMENT ON TABLE pgsafe.migration_log IS
    'One row per step of a plan applied through pgsafe.apply_plan(). A row left '
    'at outcome = running is a step that started and did not finish.';

-- Apply a plan.
--
--   p_plan is a query returning pgsafe.step rows, usually a call to one of the
--   generators: 'SELECT * FROM pgsafe.plan_set_not_null(''app.orders'', ''note'')'
--
-- A step whose statement is NULL is a deploy boundary rather than something to
-- run. The procedure records it as stopped and returns, because running on past
-- it is exactly the mistake the plan exists to prevent: the contract phase of a
-- rename belongs in a later release, not later in the same loop.
--
-- p_dry_run writes the plan into the log without running anything and without
-- committing, so it works inside a transaction and can be rolled back. The real
-- run cannot: call it from psql with no transaction open.
CREATE OR REPLACE PROCEDURE pgsafe.apply_plan(
    p_migration    text,
    p_plan         text,
    p_lock_timeout text DEFAULT '3s',
    p_attempts     integer DEFAULT 5,
    p_backoff      interval DEFAULT interval '2 seconds',
    p_dry_run      boolean DEFAULT false
)
LANGUAGE plpgsql
AS $$
DECLARE
    current_step pgsafe.step;
    previous_tx  integer := NULL;
    row_id       bigint;
    landed       pgsafe.attempt;
    applied      integer := 0;
BEGIN
    IF p_migration IS NULL OR btrim(p_migration) = '' THEN
        RAISE EXCEPTION 'a migration needs a name, so the log can be read later'
            USING ERRCODE = 'invalid_parameter_value';
    END IF;

    FOR current_step IN
        EXECUTE format(
            'SELECT step, tx, statement, lock_mode, work, note FROM (%s) AS plan ORDER BY step',
            p_plan
        )
    LOOP
        IF current_step.statement IS NULL THEN
            INSERT INTO pgsafe.migration_log
                (migration, step, tx, statement, lock_mode, work, note, outcome, finished_at)
            VALUES (p_migration, current_step.step, current_step.tx, NULL,
                    current_step.lock_mode, current_step.work, current_step.note,
                    'stopped', clock_timestamp());
            RAISE NOTICE 'step % is a deploy boundary, not a statement: %',
                         current_step.step, current_step.note;
            RAISE NOTICE 'applied % statement(s). Deploy, then run the rest.', applied;
            IF NOT p_dry_run THEN
                COMMIT;
            END IF;
            RETURN;
        END IF;

        IF p_dry_run THEN
            INSERT INTO pgsafe.migration_log
                (migration, step, tx, statement, lock_mode, work, note, outcome, finished_at)
            VALUES (p_migration, current_step.step, current_step.tx, current_step.statement,
                    current_step.lock_mode, current_step.work, current_step.note,
                    'planned', clock_timestamp());
            CONTINUE;
        END IF;

        -- A new tx number in the plan means the previous one has to be closed
        -- before the next statement starts.
        IF previous_tx IS NOT NULL AND current_step.tx <> previous_tx THEN
            COMMIT;
        END IF;
        previous_tx := current_step.tx;

        INSERT INTO pgsafe.migration_log
            (migration, step, tx, statement, lock_mode, work, note)
        VALUES (p_migration, current_step.step, current_step.tx, current_step.statement,
                current_step.lock_mode, current_step.work, current_step.note)
        RETURNING log_id INTO row_id;
        COMMIT;

        landed := pgsafe.run_guarded(
            current_step.statement, p_lock_timeout, p_attempts, p_backoff
        );
        applied := applied + 1;

        UPDATE pgsafe.migration_log
           SET outcome = 'done',
               finished_at = clock_timestamp(),
               attempts = landed.attempts
         WHERE log_id = row_id;
        COMMIT;
    END LOOP;

    IF NOT p_dry_run THEN
        COMMIT;
    END IF;
    RAISE NOTICE 'applied % statement(s) for %', applied, p_migration;
END
$$;

-- Steps that started and never finished. The query to run after a migration
-- fell over, and the reason the log row is committed before the statement.
CREATE OR REPLACE FUNCTION pgsafe.unfinished_steps()
RETURNS TABLE (
    migration  text,
    step       integer,
    statement  text,
    started_at timestamptz,
    age        interval
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT l.migration,
           l.step,
           l.statement,
           l.started_at,
           clock_timestamp() - l.started_at
      FROM pgsafe.migration_log l
     WHERE l.outcome = 'running'
     ORDER BY l.started_at;
END
$$;

-- What one migration did, with the time each statement took.
--
-- These durations are measured, and they are measured here: started_at and
-- finished_at are clock_timestamp() either side of the statement. They are the
-- only numbers in this library that come from a run rather than from a
-- document, and they exist only once somebody has run something.
CREATE OR REPLACE FUNCTION pgsafe.migration_report(p_migration text)
RETURNS TABLE (
    step      integer,
    tx        integer,
    outcome   text,
    took      interval,
    attempts  integer,
    lock_mode text,
    statement text
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pgsafe.migration_log l WHERE l.migration = p_migration) THEN
        RAISE EXCEPTION 'nothing logged for migration %', p_migration
            USING ERRCODE = 'no_data_found',
                  HINT = 'SELECT DISTINCT migration FROM pgsafe.migration_log';
    END IF;

    RETURN QUERY
    SELECT l.step,
           l.tx,
           l.outcome,
           l.finished_at - l.started_at,
           l.attempts,
           l.lock_mode,
           l.statement
      FROM pgsafe.migration_log l
     WHERE l.migration = p_migration
     ORDER BY l.step;
END
$$;
